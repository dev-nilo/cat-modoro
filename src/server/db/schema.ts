import { sql } from "drizzle-orm";
import { check, index, integer, pgTable, text, timestamp, uuid } from "drizzle-orm/pg-core";

export const SESSION_KINDS = ["focus", "short_break", "long_break"] as const;
export const SESSION_OUTCOMES = ["completed", "skipped"] as const;

export type SessionKind = (typeof SESSION_KINDS)[number];
export type SessionOutcome = (typeof SESSION_OUTCOMES)[number];

/** One finished Pomodoro phase. The id is generated by the client, which makes re-sending it idempotent. */
export const sessions = pgTable(
  "sessions",
  {
    id: uuid("id").primaryKey(),
    clientId: uuid("client_id").notNull(),
    kind: text("kind", { enum: SESSION_KINDS }).notNull(),
    outcome: text("outcome", { enum: SESSION_OUTCOMES }).notNull(),
    startedAt: timestamp("started_at", { withTimezone: true, mode: "date" }).notNull(),
    endedAt: timestamp("ended_at", { withTimezone: true, mode: "date" }).notNull(),
    plannedSeconds: integer("planned_seconds").notNull(),
    createdAt: timestamp("created_at", { withTimezone: true, mode: "date" }).notNull().defaultNow(),
  },
  (t) => [
    // The listing: one client's history, newest first.
    index("sessions_client_started_idx").on(t.clientId, t.startedAt.desc()),
    check("sessions_kind_check", sql`${t.kind} in ('focus', 'short_break', 'long_break')`),
    check("sessions_outcome_check", sql`${t.outcome} in ('completed', 'skipped')`),
    check("sessions_time_order_check", sql`${t.endedAt} >= ${t.startedAt}`),
    check("sessions_planned_check", sql`${t.plannedSeconds} > 0`),
  ],
);

export type SessionRow = typeof sessions.$inferSelect;
