/**
 * Wire format of the sessions API. These Zod schemas validate requests and are
 * also the source of the OpenAPI document, so the contract can't drift.
 */

import { z } from "zod";

import { SESSION_KINDS, SESSION_OUTCOMES } from "@/server/db/schema";
import { ApiError, type FieldError } from "@/server/http/problem";

/** Longest phase the app allows (90 min focus). */
export const MAX_PLANNED_SECONDS = 90 * 60;
/** Sanity limit: anything longer was left paused for hours and isn't a real session. */
export const MAX_SESSION_SECONDS = 4 * 60 * 60;
/** Tolerated clock skew between the client and the server. */
export const CLOCK_SKEW_MS = 5 * 60 * 1000;

export const DEFAULT_PAGE_SIZE = 20;
export const MAX_PAGE_SIZE = 100;

const timestamp = z.iso.datetime({ offset: true });

export const SessionKind = z.enum(SESSION_KINDS).meta({ description: "Which Pomodoro phase this was." });
export const SessionOutcome = z
  .enum(SESSION_OUTCOMES)
  .meta({ description: "`completed` if the timer ran out, `skipped` if the user ended it early." });

export const NewSession = z
  .object({
    id: z.uuid().meta({ description: "Generated by the client. Re-sending the same session is idempotent." }),
    kind: SessionKind,
    outcome: SessionOutcome,
    startedAt: timestamp.meta({ description: "When the phase first started running." }),
    endedAt: timestamp.meta({ description: "When the phase finished or was skipped." }),
    plannedSeconds: z
      .int()
      .min(1)
      .max(MAX_PLANNED_SECONDS)
      .meta({ description: "The phase length configured at the time." }),
  })
  .superRefine((s, ctx) => {
    const started = Date.parse(s.startedAt);
    const ended = Date.parse(s.endedAt);
    if (ended < started) {
      ctx.addIssue({ code: "custom", path: ["endedAt"], message: "must not be before startedAt" });
    } else if (ended - started > MAX_SESSION_SECONDS * 1000) {
      ctx.addIssue({ code: "custom", path: ["endedAt"], message: "a session can't last more than 4 hours" });
    }
    if (ended > Date.now() + CLOCK_SKEW_MS) {
      ctx.addIssue({ code: "custom", path: ["endedAt"], message: "must not be in the future" });
    }
  })
  .meta({ id: "NewSession", description: "A finished phase, as sent by the client." });

export type NewSession = z.infer<typeof NewSession>;

export const Session = z
  .object({
    id: z.uuid(),
    kind: SessionKind,
    outcome: SessionOutcome,
    startedAt: timestamp,
    endedAt: timestamp,
    plannedSeconds: z.int(),
    createdAt: timestamp.meta({ description: "When the server first stored it." }),
  })
  .meta({ id: "Session" });

export type Session = z.infer<typeof Session>;

export const PageInfo = z
  .object({
    number: z.int().min(0),
    size: z.int().min(1),
    totalElements: z.int().min(0),
    totalPages: z.int().min(0),
  })
  .meta({ id: "PageInfo" });

export const SessionPage = z
  .object({ content: z.array(Session), page: PageInfo })
  .meta({ id: "SessionPage", description: "One page of sessions, newest first." });

export type SessionPage = z.infer<typeof SessionPage>;

const intParam = (min: number, max: number, fallback: number) =>
  z
    .string()
    .regex(/^\d+$/, "must be a non-negative integer")
    .transform(Number)
    .pipe(z.int().min(min).max(max))
    .optional()
    .transform((v) => v ?? fallback);

export const ListQuery = z
  .object({
    page: intParam(0, Number.MAX_SAFE_INTEGER, 0),
    size: intParam(1, MAX_PAGE_SIZE, DEFAULT_PAGE_SIZE),
    from: timestamp.optional(),
    to: timestamp.optional(),
  })
  .refine((q) => !q.from || !q.to || Date.parse(q.from) < Date.parse(q.to), {
    path: ["to"],
    message: "must be after from",
  });

export type ListQuery = z.infer<typeof ListQuery>;

/** Parses `input` or throws a 400 validation problem listing every bad field. */
export function parseOrThrow<T extends z.ZodType>(schema: T, input: unknown, where: "body" | "query"): z.infer<T> {
  const result = schema.safeParse(input);
  if (result.success) return result.data;
  const errors: FieldError[] = result.error.issues.map((issue) => ({
    field: [where, ...issue.path].join("."),
    message: issue.message,
  }));
  throw new ApiError("validation", `The ${where} has ${errors.length} invalid field(s).`, errors);
}
